def _redirect(location: str) -> httpx.Response:
    return httpx.Response(301, headers={"Location": location, "Server": "cloudflare"}, text="")


def _handler(now: datetime):
    expires = (now + timedelta(days=200)).strftime("%Y-%m-%dT%H:%M:%SZ")

    def handle(request: httpx.Request) -> httpx.Response:
        host = request.url.host
        scheme = request.url.scheme
        path = request.url.path

        if host == f"www.{DOMAIN}":
            if scheme == "http":
                return _redirect(f"https://www.{DOMAIN}{path}")
            if path == "/.well-known/security.txt":
                return httpx.Response(200, text=SECURITY_TXT_VALID.format(expires=expires),
                                      headers={"Content-Type": "text/plain"})
            if path == "/robots.txt":
                return httpx.Response(200, text="User-agent: *\nDisallow: /search\n", headers={"Content-Type": "text/plain"})
            return httpx.Response(
                200,
                html=WWW_HTML,
                headers=[
                    ("Server", "cloudflare"),
                    ("Content-Security-Policy",
                     "default-src 'self'; script-src 'self' 'unsafe-inline' https://www.googletagmanager.com; "
                     "style-src 'self' https://fonts.googleapis.com; frame-ancestors 'none'; object-src 'none'"),
                    *STRONG_HEADERS,
                    ("Set-Cookie", "__Host-acme_pref=lang-en; Path=/; Secure; HttpOnly; SameSite=Lax"),
                    ("Cache-Control", "public, max-age=300"),
                ],
            )

        if host == f"app.{DOMAIN}":
            if scheme == "http":
                return _redirect(f"https://app.{DOMAIN}{path}")
