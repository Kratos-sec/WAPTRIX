class DemoTLSInspector:
    """Deterministic TLS observations for the demo hosts."""

    def __init__(self, now: datetime) -> None:
        self.now = now

    async def inspect(self, target: Target) -> TLSInfo:
        host = target.host
        base = dict(
            host=host,
            port=443,
            protocol="TLSv1.3",
            cipher="TLS_AES_256_GCM_SHA384",
            cipher_bits=256,
            cert_issuer="countryName=US, organizationName=Let's Encrypt, commonName=R11",
            cert_subject=f"commonName=*.{DOMAIN}",
            cert_serial="4a1f9be20c3d7e",
            cert_not_before=self.now - timedelta(days=40),
            cert_not_after=self.now + timedelta(days=50),
            days_to_expiry=50,
            san=[f"*.{DOMAIN}", DOMAIN],
            hostname_match=True,
            trusted=True,
            legacy_probe="completed",
        )
        if host == f"app.{DOMAIN}":
            base.update(protocol="TLSv1.2", cipher="ECDHE-RSA-AES128-GCM-SHA256", cipher_bits=128,
                        cert_not_after=self.now + timedelta(days=12), days_to_expiry=12)
        elif host == f"api.{DOMAIN}":
            base.update(protocol="TLSv1.2", cipher="ECDHE-RSA-AES256-GCM-SHA384")
        elif host == f"admin.{DOMAIN}":
            base.update(
                protocol="TLSv1.2",
                cipher="ECDHE-RSA-DES-CBC3-SHA",
                cipher_bits=112,
                cert_subject="commonName=acme-admin-internal",
                cert_issuer="commonName=acme-admin-internal",
                cert_not_before=self.now - timedelta(days=800),
                cert_not_after=self.now - timedelta(days=35),
                days_to_expiry=-35,
                san=["acme-admin-internal", "localhost"],
                self_signed=True,
                hostname_match=False,
                trusted=False,
                verify_error="self-signed certificate",
                legacy_protocols_accepted=["TLSv1"],
            )
        elif host == f"legacy.{DOMAIN}":
            return TLSInfo(host=host, port=443, error="TLS handshake failed: [Errno 61] Connection refused")
        return TLSInfo(**base)


async def _demo_resolver(host: str) -> list[str]:
    if host not in _ADDRESSES:
        raise OSError(f"{host} not in demo zone")
    return _ADDRESSES[host]


async def build_demo_audit(now: datetime | None = None) -> AuditResult:
    now = now or datetime.now(timezone.utc)
    request = AuditRequest(
        subdomains=[*SUBDOMAINS, "https://www.acme-corp.example/", "*.acme-corp.example", "vendor-portal.example.net"],
        authorization_ref=DEMO_AUTH_REF,
        scope_domains=[DOMAIN],
        requests_per_second=10,
        # The demo zone resolves to RFC 5737 documentation ranges, which the scope guard treats as reserved.
        allow_private=True,
    )
    auditor = PassiveAuditor(
        request,
        transport=httpx.MockTransport(_handler(now)),
        tls_inspector=DemoTLSInspector(now),
        resolver=_demo_resolver,
    )
    result = await auditor.run(audit_id=DEMO_ID)
    result.demo = True
    return result


def load_demo_audit() -> AuditResult:
    """Load the bundled demo dataset, regenerating it if the file is missing or stale."""
    if DEMO_PATH.exists():
        try:
            return AuditResult.model_validate_json(DEMO_PATH.read_text(encoding="utf-8"))
        except ValueError:
            pass
    result = asyncio.run(build_demo_audit())
    write_demo(result)
    return result


async def aload_demo_audit() -> AuditResult:
    if DEMO_PATH.exists():
        try:
            return AuditResult.model_validate_json(DEMO_PATH.read_text(encoding="utf-8"))
        except ValueError:
            pass
    result = await build_demo_audit()
    write_demo(result)
    return result


def write_demo(result: AuditResult) -> Path:
    DEMO_PATH.write_text(json.dumps(json.loads(result.model_dump_json()), indent=2) + "\n", encoding="utf-8")
    return DEMO_PATH


